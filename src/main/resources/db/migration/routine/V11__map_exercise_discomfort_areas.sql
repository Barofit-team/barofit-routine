-- NONE은 사용자 선택 값이며 종목 부위로 저장하지 않는다.
CREATE TABLE routine.exercise_discomfort_area (
  exercise_id VARCHAR(50) NOT NULL REFERENCES routine.exercise(id),
  area VARCHAR(20) NOT NULL CHECK (area IN ('NECK_SHOULDER', 'ARM_WRIST', 'BACK', 'LEG_ANKLE')),
  PRIMARY KEY (exercise_id, area)
);
